"""Structural checks for the split external-conditioning example workflows.

The examples are generated by ``tools/build_example_workflows.py`` from the API
prompts in ``workflows/``; these tests make sure the generated graphs stay wired
the way the two-job workflow requires.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = ROOT / "examples"
WORKFLOWS = ROOT / "workflows"
REGISTRY_ID = "herrgotts-h3-infinite-continuation-suite"
RELEASE_VERSION = "1.4.0"

JOB1 = EXAMPLES / "Herrgotts_H3_Infinite_v1.5_ExternalConditioning_01_Start.json"
JOB2 = EXAMPLES / "Herrgotts_H3_Infinite_v1.5_ExternalConditioning_02_Continue.json"


def _load(path):
    return json.loads(path.read_text(encoding="utf-8"))


def _nodes(data, node_type):
    return [n for n in data["nodes"] if n.get("type") == node_type]


def _node(data, node_type):
    return next(n for n in data["nodes"] if n.get("type") == node_type)


def _input(node, name):
    return next(i for i in node["inputs"] if i.get("name") == name)


def _link_source(data, node, name):
    link = next(l for l in data["links"] if l[0] == _input(node, name)["link"])
    by_id = {n["id"]: n for n in data["nodes"]}
    return by_id[link[1]]["type"], link[2]


def test_both_examples_exist_and_are_valid_graphs():
    for path in (JOB1, JOB2):
        data = _load(path)
        assert isinstance(data.get("nodes"), list) and data["nodes"]
        assert isinstance(data.get("links"), list)
        for node in data["nodes"]:
            assert "type" in node and "id" in node and "widgets_values" in node


def test_every_link_resolves_to_a_real_node_and_slot():
    for path in (JOB1, JOB2):
        data = _load(path)
        ids = {n["id"] for n in data["nodes"]}
        by_id = {n["id"]: n for n in data["nodes"]}
        for link_id, origin, origin_slot, target, target_slot, link_type in data["links"]:
            assert origin in ids, (path.name, link_id)
            assert target in ids, (path.name, link_id)
            assert origin_slot < len(by_id[origin]["outputs"]), (path.name, link_id)
            assert target_slot < len(by_id[target]["inputs"]), (path.name, link_id)


def test_job1_uses_start_external_conditioning_and_ignores_encoder_latent():
    data = _load(JOB1)
    start = _node(data, "H3ContinuousStartExternalConditioning")
    encoder = _node(data, "MiniMaxH3FantasticRefModTextEncode")
    sampler = _node(data, "KSamplerSelect")  # sanity: known node present
    assert sampler is not None

    assert _link_source(data, start, "conditioning") == ("MiniMaxH3FantasticRefModTextEncode", 0)
    assert _link_source(data, start, "reference_map") == ("MiniMaxH3FantasticRefModTextEncode", 1)
    for name in ("first_frame", "last_frame"):
        assert _input(start, name)["link"] is None
    # Job 1 takes width/height from the live megapixel node; the widget values are
    # only its fallback defaults.
    assert start["widgets_values"][2] == 5.0
    assert _link_source(data, start, "width") == ("ImageDimensionsFromMegaPixels", 0)
    assert _link_source(data, start, "height") == ("ImageDimensionsFromMegaPixels", 1)

    # The unused encoder latent must not feed anything.
    assert encoder["outputs"][2]["links"] is None
    latent_consumers = [
        link for link in data["links"] if link[1] == encoder["id"] and link[2] == 2
    ]
    assert latent_consumers == []
    del sampler


def test_job1_sampler_and_guider_take_the_external_node_outputs():
    data = _load(JOB1)
    start = _node(data, "H3ContinuousStartExternalConditioning")
    sampler = _node(data, "SamplerCustomAdvanced")
    guider = _node(data, "BasicGuider")
    assert _link_source(data, sampler, "latent_image") == ("H3ContinuousStartExternalConditioning", 1)
    assert _link_source(data, guider, "conditioning") == ("H3ContinuousStartExternalConditioning", 0)
    assert start is not None


def test_job1_saves_clip_one_and_renders_stitch_ready():
    data = _load(JOB1)
    save = _node(data, "H3ContinuousSaveLatent")
    output = _node(data, "H3ContinuousStitchOutputV14")
    analyzer = _node(data, "H3ContinuousAnalyzeHandoverV14")

    assert save["widgets_values"][:2] == ["h3_external_conditioning/shot", 1]
    assert _link_source(data, save, "handover") == ("H3ContinuousAnalyzeHandoverV14", 0)
    assert _link_source(data, output, "handover") == ("H3ContinuousAnalyzeHandoverV14", 0)
    assert output["widgets_values"][0] == "Stitch Ready"
    assert analyzer["widgets_values"][0] == "Balanced"
    assert analyzer["widgets_values"][4] == "39"


def test_job2_continues_from_saved_clip_one_with_handover():
    data = _load(JOB2)
    load = _node(data, "H3ContinuousLoadLatent")
    cont = _node(data, "H3ContinuousContinueExternalConditioning")

    assert load["widgets_values"] == ["h3_external_conditioning/shot", 1]
    assert _link_source(data, cont, "previous_latent") == ("H3ContinuousLoadLatent", 0)
    assert _link_source(data, cont, "handover") == ("H3ContinuousLoadLatent", 3)
    assert _link_source(data, cont, "conditioning") == ("MiniMaxH3FantasticRefModTextEncode", 0)

    # Widget order: width, height, duration, masked_context_frames, duration_mode,
    # audio_tail_carryover, audio_feather_ticks.
    assert cont["widgets_values"] == [704, 704, 5.0, "39", "Net New Content", "Full Previous Tail", 0]


def test_job2_has_no_first_frame_and_no_clip_socket():
    data = _load(JOB2)
    cont = _node(data, "H3ContinuousContinueExternalConditioning")
    names = [i.get("name") for i in cont["inputs"]]
    assert "first_frame" not in names
    assert "clip" not in names
    assert "prompt" not in names
    assert "reference_map" in names


def test_job2_saves_clip_two_and_records_head_context():
    data = _load(JOB2)
    cont = _node(data, "H3ContinuousContinueExternalConditioning")
    save = _node(data, "H3ContinuousSaveLatent")
    output = _node(data, "H3ContinuousStitchOutputV14")

    assert save["widgets_values"][:2] == ["h3_external_conditioning/shot", 2]
    assert _link_source(data, save, "head_context_frames") == (
        "H3ContinuousContinueExternalConditioning", 2)
    assert output["widgets_values"][0] == "Final Clip"
    assert _link_source(data, output, "head_context_frames") == (
        "H3ContinuousContinueExternalConditioning", 2)
    assert cont is not None


def test_examples_carry_registry_metadata():
    for path in (JOB1, JOB2):
        data = _load(path)
        for node in data["nodes"]:
            if str(node.get("type", "")).startswith("H3Continuous"):
                props = node.get("properties", {})
                assert props.get("cnr_id") == REGISTRY_ID, (path.name, node["type"])
                assert props.get("ver") == RELEASE_VERSION, (path.name, node["type"])
                assert props.get("Node name for S&R") == node["type"]


def test_api_prompts_match_the_examples_node_for_node():
    """The API prompts are the source of truth for both examples."""
    for api_path, example_path in (
        (WORKFLOWS / "job1_start_api.json", JOB1),
        (WORKFLOWS / "job2_continue_api.json", JOB2),
    ):
        api = _load(api_path)
        example = _load(example_path)
        by_class = {}
        for node in example["nodes"]:
            by_class.setdefault(node["type"], []).append(node)
        api_classes = {}
        for node in api.values():
            api_classes.setdefault(node["class_type"], []).append(node)
        assert set(by_class) == set(api_classes), (api_path.name, set(by_class) ^ set(api_classes))
        for class_type, nodes in api_classes.items():
            assert len(nodes) == len(by_class[class_type]), (api_path.name, class_type)


def test_stitch_job_is_a_separate_disk_state_job():
    """The stitcher reads its inputs from disk, so it cannot share a prompt with
    the Save AV Latent node that produces them (it would run first and skip)."""
    stitch_api = _load(WORKFLOWS / "job3_stitch_api.json")
    classes = {node["class_type"] for node in stitch_api.values()}
    assert "H3ContinuousStitchSavedChainV14" in classes
    assert "H3ContinuousSaveLatent" not in classes
    assert "H3ContinuousContinueExternalConditioning" not in classes

    continue_api = _load(WORKFLOWS / "job2_continue_api.json")
    continue_classes = {node["class_type"] for node in continue_api.values()}
    assert "H3ContinuousStitchSavedChainV14" not in continue_classes
    assert "H3ContinuousSaveLatent" in continue_classes
